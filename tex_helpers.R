# =============================================================================
# tex_helpers.R
# Shared helpers for writing LaTeX outputs that Overleaf documents \input.
#
# Sourced by 7_export_tex.R. Later scripts (measurement, models) can source it
# too and write their own numbers/tables into tex_outputs/.
#
#   tex_outputs/
#   ├── numbers_<name>.tex   \newcommand macros for every number cited in text
#   └── tables/*.tex         booktabs tabular bodies (caption + label stay in
#                            the Overleaf document, so they stay editable there)
#
# Figures are not copied here: sync_overleaf.R copies graphical_output/ and
# study_exhibits/ straight into the Overleaf project.
#
# Conventions
# - Macro names are letters only (LaTeX does not allow digits): \nPairs, not \n_pairs.
# - Macros hold the bare number, no % sign: write  \pctSameLength\%  in the text.
# - Follow a macro with {} when a space comes next:  \nPairs{} pairs.
# - Numbers are rounded half-up (52.5 -> 53), unlike R's round() (52.5 -> 52).
# =============================================================================

TEX_DIR <- "tex_outputs"

# ---- Formatting --------------------------------------------------------------

# Round half away from zero, so numbers match what you'd write by hand.
round_half_up <- function(x, digits = 0) {
  m <- 10^digits
  sign(x) * floor(abs(x) * m + 0.5 + 1e-9) / m
}

# Format a number for LaTeX: thousands separator, fixed decimals, real minus sign.
# plus = TRUE adds a "+" to positive values (for differences).
tex_num <- function(x, digits = 0, plus = FALSE, big_mark = ",") {
  x <- as.numeric(x)
  out <- formatC(round_half_up(abs(x), digits), format = "f", digits = digits,
                 big.mark = big_mark)
  out <- ifelse(x < 0 & round_half_up(abs(x), digits) > 0, paste0("$-$", out), out)
  if (plus) out <- ifelse(x > 0 & round_half_up(x, digits) > 0, paste0("+", out), out)
  ifelse(is.na(x), "--", out)
}

# Parse numbers that were written to CSV as text ("9,789", "18.6%").
parse_csv_num <- function(x) as.numeric(gsub("[,%]", "", x))

# Escape LaTeX special characters in free text (table cells, labels).
tex_escape <- function(x) {
  x <- as.character(x)
  x <- gsub("\\", "\\textbackslash{}", x, fixed = TRUE)
  for (ch in c("&", "%", "$", "#", "_", "{", "}")) {
    x <- gsub(ch, paste0("\\", ch), x, fixed = TRUE)
  }
  x <- gsub("~", "\\textasciitilde{}", x, fixed = TRUE)
  x <- gsub("^", "\\textasciicircum{}", x, fixed = TRUE)
  # Restore the escaped braces produced by \textbackslash{} etc.
  x <- gsub("\\textbackslash\\{\\}", "\\textbackslash{}", x, fixed = TRUE)
  x <- gsub("\\textasciitilde\\{\\}", "\\textasciitilde{}", x, fixed = TRUE)
  x <- gsub("\\textasciicircum\\{\\}", "\\textasciicircum{}", x, fixed = TRUE)
  x
}

# ---- Number macros -----------------------------------------------------------
# Usage:
#   tex_macros_start()
#   tex_macro("nPairs", tex_num(8150), "Pairs in post-ID sample", "data_checks/0b_sample_comparison.csv")
#   tex_macros_write("numbers_update.tex")

.tex_macros <- new.env()

tex_macros_start <- function() {
  .tex_macros$rows <- data.frame(name = character(), value = character(),
                                 label = character(), source = character(),
                                 section = character(), stringsAsFactors = FALSE)
  .tex_macros$section <- ""
  invisible(NULL)
}

# Group the following macros under a heading comment in the output file.
tex_section <- function(title) {
  .tex_macros$section <- title
  invisible(NULL)
}

tex_macro <- function(name, value, label = "", source = "") {
  if (!grepl("^[A-Za-z]+$", name)) {
    stop(sprintf("Macro name '%s' must be letters only (no digits, _ or -).", name))
  }
  if (name %in% .tex_macros$rows$name) stop(sprintf("Macro '%s' defined twice.", name))
  if (length(value) != 1 || is.na(value)) stop(sprintf("Macro '%s' has no single value.", name))
  .tex_macros$rows <- rbind(.tex_macros$rows, data.frame(
    name = name, value = as.character(value), label = label, source = source,
    section = .tex_macros$section, stringsAsFactors = FALSE))
  invisible(value)
}

tex_macros_write <- function(file, dir = TEX_DIR, script = "") {
  dir.create(dir, showWarnings = FALSE, recursive = TRUE)
  rows <- .tex_macros$rows
  name_w <- max(nchar(rows$name)) + 3
  out <- c(
    "% =============================================================================",
    sprintf("%% %s -- AUTO-GENERATED by %s. Do not edit by hand:", file, script),
    "% re-run the script and sync instead. Edits made in Overleaf are overwritten.",
    "%",
    "% Usage in text:  \\nPairs{} pairs   |   \\pctSameLength\\%   |   [\\ciLow, \\ciHigh]",
    "% ============================================================================="
  )
  for (sec in unique(rows$section)) {
    r <- rows[rows$section == sec, ]
    if (nzchar(sec)) out <- c(out, "", paste0("% ---- ", sec, " ", strrep("-", max(3, 70 - nchar(sec)))))
    src_prev <- ""
    for (i in seq_len(nrow(r))) {
      if (nzchar(r$source[i]) && r$source[i] != src_prev) {
        out <- c(out, paste0("% source: ", r$source[i]))
        src_prev <- r$source[i]
      }
      def <- sprintf("\\newcommand{\\%s}{%s}", r$name[i], r$value[i])
      pad <- strrep(" ", max(1, name_w + 16 + 14 - nchar(def)))
      out <- c(out, if (nzchar(r$label[i])) paste0(def, pad, "% ", r$label[i]) else def)
    }
  }
  path <- file.path(dir, file)
  writeLines(out, path, useBytes = TRUE)
  message(sprintf("Wrote %d macros -> %s", nrow(rows), path))
  invisible(path)
}

# Two-line column heading without extra LaTeX packages: stack_head("Pairs from", "2015--17")
stack_head <- function(top, bottom, align = "c") {
  sprintf("\\begin{tabular}[b]{@{}%s@{}}%s\\\\ %s\\end{tabular}", align, top, bottom)
}

# ---- Tables ------------------------------------------------------------------
# Writes only the tabular environment. Wrap it in Overleaf:
#   \begin{table}[htbp]
#     \centering
#     \caption{...}\label{tab:...}
#     \input{tex_outputs/tables/<name>}
#     \tablenote{...}            % optional
#   \end{table}
#
# df       data frame of cells (already formatted as text; cells are escaped
#          unless escape = FALSE or the column is listed in raw_cols)
# align    column spec, e.g. "lrrr" or ">{\\raggedright}p{4cm}rr"
# header   column headings (escaped); a list element of length > 1 is ignored
# midrule_after  row numbers after which to draw a \midrule
# group_rows     optional named list: heading -> first row index of a block

tex_table <- function(df, file, align = NULL, header = names(df),
                      escape = TRUE, raw_cols = character(), raw_header = FALSE,
                      midrule_after = integer(), group_rows = NULL,
                      dir = file.path(TEX_DIR, "tables"), script = "") {
  dir.create(dir, showWarnings = FALSE, recursive = TRUE)
  df <- as.data.frame(df, stringsAsFactors = FALSE)
  if (is.null(align)) {
    align <- paste0("l", strrep("r", ncol(df) - 1))
  }
  cells <- df
  for (j in seq_along(cells)) {
    v <- as.character(cells[[j]])
    v[is.na(v)] <- "--"
    # Cells that are only numbers formatted by tex_num() (digits, signs, $-$,
    # commas, brackets) are left as they are; everything else is escaped.
    is_num <- nzchar(v) & gsub("\\$-\\$|[0-9.,+ ]|\\[|\\]", "", v, perl = TRUE) == ""
    if (escape && !(names(cells)[j] %in% raw_cols)) v[!is_num] <- tex_escape(v[!is_num])
    cells[[j]] <- v
  }
  head_txt <- if (raw_header) header else tex_escape(header)
  body <- character()
  group_starts <- if (!is.null(group_rows)) unlist(group_rows) else integer()
  for (i in seq_len(nrow(cells))) {
    if (i %in% group_starts) {
      g <- names(group_rows)[group_starts == i]
      if (i > 1) body <- c(body, "\\addlinespace")
      body <- c(body, sprintf("\\multicolumn{%d}{l}{\\textit{%s}} \\\\", ncol(cells), tex_escape(g)))
    }
    body <- c(body, paste0(paste(unlist(cells[i, ]), collapse = " & "), " \\\\"))
    if (i %in% midrule_after) body <- c(body, "\\midrule")
  }
  out <- c(
    sprintf("%% AUTO-GENERATED by %s -- do not edit by hand.", script),
    sprintf("\\begin{tabular}{%s}", align),
    "\\toprule",
    paste0(paste(head_txt, collapse = " & "), " \\\\"),
    "\\midrule",
    body,
    "\\bottomrule",
    "\\end{tabular}"
  )
  path <- file.path(dir, paste0(file, ".tex"))
  writeLines(out, path, useBytes = TRUE)
  message(sprintf("Wrote table -> %s", path))
  invisible(path)
}
